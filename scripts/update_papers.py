#!/usr/bin/env python3
"""Fetch recent papers from INSPIRE-HEP and write them to papers-feed.js.

Run by .github/workflows/update-papers.yml on a schedule, so the site loads a
static file instead of querying arXiv from the visitor's browser.
"""
import json
import sys
import urllib.parse
import urllib.request
from pathlib import Path

AUTHOR_BAI = 'D.Rankin.1'
# Large-collaboration papers (e.g. CMS, thousands of authors) are excluded.
MAX_AUTHOR_COUNT = 1000
NUM_PAPERS = 20
OUTPUT = Path(__file__).resolve().parent.parent / 'papers-feed.js'

FIELDS = [
    'titles.title',
    'authors.full_name',
    'author_count',
    'arxiv_eprints.value',
    'dois.value',
    'publication_info',
    'preprint_date',
    'earliest_date',
    'control_number',
]


def fetch_records():
    params = urllib.parse.urlencode({
        'q': f'a {AUTHOR_BAI} and ac < {MAX_AUTHOR_COUNT}',
        'sort': 'mostrecent',
        'size': NUM_PAPERS,
        'fields': ','.join(FIELDS),
    })
    url = f'https://inspirehep.net/api/literature?{params}'
    request = urllib.request.Request(url, headers={'Accept': 'application/json'})
    with urllib.request.urlopen(request, timeout=60) as response:
        return json.load(response)['hits']['hits']


def format_name(full_name):
    # INSPIRE lists the PI under several variants (e.g. "Rankin, Dylan Sheldon").
    if full_name.startswith('Rankin, D'):
        return 'Dylan Rankin'
    # INSPIRE stores names as "Last, First"; display as "First Last".
    if ', ' in full_name:
        last, first = full_name.split(', ', 1)
        return f'{first} {last}'
    return full_name


def normalize(record):
    meta = record['metadata']
    title = ' '.join(meta.get('titles', [{}])[0].get('title', 'Untitled').split())
    published = (meta.get('preprint_date') or meta.get('earliest_date') or '')[:10]

    if meta.get('arxiv_eprints'):
        link = f"https://arxiv.org/abs/{meta['arxiv_eprints'][0]['value']}"
    elif meta.get('dois'):
        link = f"https://doi.org/{meta['dois'][0]['value']}"
    else:
        link = f"https://inspirehep.net/literature/{meta['control_number']}"

    names = [format_name(a['full_name']) for a in meta.get('authors', [])]
    if meta.get('author_count', len(names)) > 20:
        authors = f"{', '.join(names[:5])} et al."
    else:
        authors = ', '.join(names)

    return {
        'title': title,
        'published': published,
        'link': link,
        'authors': authors,
        'authorCount': meta.get('author_count', len(names)),
        'journal': format_journal(meta.get('publication_info', [])),
    }


def format_journal(publication_info):
    # e.g. "SciPost Phys. 21, 053 (2026)"; empty for preprints and proceedings.
    for info in publication_info:
        if not info.get('journal_title'):
            continue
        ref = info['journal_title']
        if info.get('journal_volume'):
            ref += f" {info['journal_volume']}"
        article = info.get('artid') or info.get('page_start')
        if article:
            ref += f', {article}'
        if info.get('year'):
            ref += f" ({info['year']})"
        return ref
    return ''


def main():
    papers = [normalize(record) for record in fetch_records()]
    if not papers:
        # Keep the previous file rather than publishing an empty list.
        sys.exit('INSPIRE returned no papers; leaving papers-feed.js unchanged.')

    body = json.dumps(papers, indent=4, ensure_ascii=False)
    OUTPUT.write_text(
        '// Generated by scripts/update_papers.py from INSPIRE-HEP. Do not edit by hand;\n'
        '// add papers missing from INSPIRE to papers-data.js instead.\n'
        f'window.FEED_PAPERS = {body};\n',
        encoding='utf-8',
    )
    print(f'Wrote {len(papers)} papers to {OUTPUT.name}')


if __name__ == '__main__':
    main()
